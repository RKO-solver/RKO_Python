def _json_bytes(value: Any) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False, sort_keys=True) + "\n").encode("utf-8")


def _write_json(path: Path, value: Any) -> None:
    path.write_bytes(_json_bytes(value))


def _snapshot_tokens(value: Any, type_info: NativeType) -> list[str]:
    if type_info.kind == "list" and type_info.item is not None:
        tokens = [str(len(value))]
        for item in value:
            tokens.extend(_snapshot_tokens(item, type_info.item))
        return tokens
    if type_info.kind == "tuple":
        tokens: list[str] = []
        for item, item_type in zip(value, type_info.items):
            tokens.extend(_snapshot_tokens(item, item_type))
        return tokens
    if type_info.kind == "bool":
        return ["1" if value else "0"]
    if type_info.kind == "int64":
        return [str(value)]
    if type_info.kind == "float64":
        return [repr(float(value))]
    raise ValueError(f"cannot serialize V1 type {type_info.display()}")


def _instance_text(ir: EnvironmentIR) -> str:
    lines = ["RKO_NATIVE_DATA_V1"]
    for field in ir.data_fields:
        lines.append(" ".join(_snapshot_tokens(field.value, field.type)))
    return "\n".join(lines) + "\n"


def _schema_data(ir: EnvironmentIR) -> dict[str, Any]:
    return {
        "language_version": LANGUAGE_VERSION,
        "class_name": ir.class_name,
        "tam_solution": ir.tam_solution,
        "fields": [field.to_data(include_value=False) for field in ir.data_fields],
    }


def _providers_used(ir: EnvironmentIR) -> list[dict[str, Any]]:
    providers: dict[str, dict[str, Any]] = {
        "rko.native.builtins": {
            "name": "rko.native.builtins",
            "version": "1",
            "semantics": "RKO Native V1 finite numeric and container runtime",
        }
    }
    for function in ir.functions.values():
        for node in ast.walk(function.node):
            if isinstance(node, ast.Call):
                rendered = ast.unparse(node.func)
                if rendered.endswith("argsort"):
                    providers["numpy.argsort.stable.float64_1d"] = {
                        "name": "numpy.argsort.stable.float64_1d",
                        "version": "1",
                        "semantics": "finite float64, 1D, kind='stable'",
                    }
                if isinstance(node.func, ast.Name) and node.func.id == "round":
                    providers["python.round.float64.decimal"] = {
                        "name": "python.round.float64.decimal",
                        "version": "1",
                        "semantics": "finite float64, ties-to-even, non-negative constant ndigits",
                    }
                canonical = rendered
                if isinstance(node.func, ast.Name):
                    canonical = ir.import_aliases.get(node.func.id, rendered)
                if canonical.startswith("math."):
                    providers["rko.native.math"] = {
                        "name": "rko.native.math",
                        "version": "1",
                        "semantics": "finite float64 mapped to C++ standard math",
                    }
    return [providers[name] for name in sorted(providers)]


def analyze_environment(env: Any) -> dict[str, Any]:
    """Analyze an initialized environment and return a structured V1 report."""
    from .gera_tabela_simbolos import build_environment_ir
    try:
        ir = build_environment_ir(env)
    except NativeCompileError as error:
        return {
            "language_version": LANGUAGE_VERSION,
            "supported": False,
            "diagnostics": [error.diagnostic.to_data()],
        }
    return {
        "language_version": LANGUAGE_VERSION,
        "supported": True,
        "class_name": ir.class_name,
        "source_file": ir.source_file,
        "function_order": ir.function_order,
        "functions": {
            name: function.to_data() for name, function in sorted(ir.functions.items())
        },
        "data_schema": _schema_data(ir),
        "providers": _providers_used(ir),
        "diagnostics": [],
    }


def compile_environment(env: Any, output_directory: str | Path) -> CompilationArtifact:
    """Compile an initialized V1 environment into Problem.h and an instance snapshot."""
    from .gera_tabela_simbolos import build_environment_ir
    output = Path(output_directory).resolve()
    output.mkdir(parents=True, exist_ok=True)
    try:
        ir = build_environment_ir(env)
    except NativeCompileError as error:
        _write_json(
            output / "compile_report.json",
            {
                "language_version": LANGUAGE_VERSION,
                "supported": False,
                "diagnostics": [error.diagnostic.to_data()],
            },
        )
        raise

    typed_ir_data = ir.to_data()
    schema_data = _schema_data(ir)
    instance_text = _instance_text(ir)
    problem_header_text = emit_problem_header(ir)
    report_data = analyze_environment(env)

    source_path = output / "environment_source.py.txt"
    ast_path = output / "environment_ast.txt"
    typed_ir_path = output / "typed_ir.json"
    schema_path = output / "instance_schema.json"
    instance_path = output / "instance.rko-data"
    problem_path = output / "Problem.h"
    report_path = output / "compile_report.json"
    manifest_path = output / "manifest.json"

    source_path.write_text(ir.source_text, encoding="utf-8")
    source_tree = ast.parse(ir.source_text, filename=ir.source_file, type_comments=True)
    ast_path.write_text(ast.dump(source_tree, indent=2, include_attributes=True) + "\n", encoding="utf-8")
    _write_json(typed_ir_path, typed_ir_data)
    _write_json(schema_path, schema_data)
    instance_path.write_text(instance_text, encoding="utf-8", newline="\n")
    problem_path.write_text(problem_header_text, encoding="utf-8", newline="\n")
    _write_json(report_path, report_data)
    _write_json(
        manifest_path,
        {
            "language_version": LANGUAGE_VERSION,
            "class_name": ir.class_name,
            "source_file": ir.source_file,
            "source_sha256": sha256(ir.source_text.encode("utf-8")).hexdigest(),
            "typed_ir_sha256": sha256(_json_bytes(typed_ir_data)).hexdigest(),
            "schema_sha256": sha256(_json_bytes(schema_data)).hexdigest(),
            "instance_sha256": sha256(instance_text.encode("utf-8")).hexdigest(),
            "problem_header_sha256": sha256(problem_header_text.encode("utf-8")).hexdigest(),
        },
    )
    return CompilationArtifact(
        output_directory=output,
        problem_header=problem_path,
        instance_data=instance_path,
        schema=schema_path,
        typed_ir=typed_ir_path,
        report=report_path,
        environment_ir=ir,
    )
