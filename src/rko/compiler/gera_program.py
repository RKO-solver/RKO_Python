    def cpp_type(self, type_info: NativeType) -> str:
        if type_info.kind == "bool":
            return "bool"
        if type_info.kind == "int64":
            return "std::int64_t"
        if type_info.kind == "float64":
            return "double"
        if type_info.kind == "none":
            return "void"
        if type_info.kind == "list" and type_info.item is not None:
            return f"std::vector<{self.cpp_type(type_info.item)}>"
        if type_info.kind == "tuple":
            return f"std::tuple<{', '.join(self.cpp_type(item) for item in type_info.items)}>"
        raise NativeCompileError(
            Diagnostic("RKO-NATIVE-CPP-001", f"no C++ type for {type_info.display()}")
        )

